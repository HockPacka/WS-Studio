"""Build small, exact phase-2 diagnostic fixtures; never installs spells or SQL."""
import argparse
import hashlib
import json
from pathlib import Path
from wildstar_spells.schema import read_tbl, Dbc
from ws_azerothcore_install import Server

ROOT=Path(__file__).resolve().parents[1]
def lua(value):
    if value is None:return 'nil'
    if isinstance(value,bool):return str(value).lower()
    if isinstance(value,(int,float)):return repr(value)
    if isinstance(value,str):return json.dumps(value,ensure_ascii=True)
    return '{'+','.join('['+lua(k)+']='+lua(v) for k,v in value.items())+'}'

def build(client,core):
    native=client/'ClientData/DB'
    prereqs=read_tbl(native/'Prerequisite.tbl')
    effects=read_tbl(native/'Spell4Effects.tbl')
    spells=read_tbl(native/'Spell4.tbl')
    bases=read_tbl(native/'Spell4Base.tbl')
    formulas=read_tbl(native/'GameFormula.tbl')
    formula=formulas.index()[1266]
    direct=effects.index()[89943]
    assert direct['spellId']==398 and direct['effectType']==8 and direct['damageType']==1
    selected={r['ID']:r for r in effects.rows if r['spellId']==55543}
    required={r['prerequisiteIdCasterApply'] for r in selected.values()}
    rows=prereqs.index();out={}
    def visit(id):
        if not id or id in out:return
        row=rows[id];out[id]=row
        for i in range(3):
            if row['prerequisiteTypeId'+str(i)]==11:visit(row['objectId'+str(i)])
    for id in sorted(required):visit(id)
    # Explicit separate namespaces: retain all tiers of the three possible base
    # interpretations and the exact raw-ID collisions for inspection. No dispatch
    # rule is inferred from the fact that a number exists in either table.
    base_ids={e['dataBits00'] for e in selected.values()}|{35927}
    raw_ids={e['dataBits00'] for e in selected.values()}|{55543}
    base_index=bases.index();instances={};tiers={}
    for r in spells.rows:
        bid=r['spell4BaseIdBaseSpell']
        if bid in base_ids or r['ID'] in raw_ids:
            b=base_index[bid]
            instances[r['ID']]={'id':r['ID'],'baseId':bid,'tier':r['tierIndex'],
                'nativeClass':b['classIdPlayer'],'description':r['description']}
            tiers.setdefault(bid,{}).setdefault(r['tierIndex'],{})[r['ID']]=True
    data=Server(core).data  # Reads config only. No SQL/credentials in output.
    dbc_receipts={}
    for label,path in [('client',client/'WoWOverride/DBFilesClient/Spell.dbc'),('server',data/'dbc/Spell.dbc')]:
        raw=path.read_bytes();dbc=Dbc(raw);heal=next(r for r in dbc.rows if r[0]==2050)
        assert 10 in heal[71:74], '2050 is not a healing spell in '+label
        dbc_receipts[label]={'sha256':hashlib.sha256(raw).hexdigest(),'healSpell':2050}
    return {'formatVersion':3,'nativeRuntimeReady':False,'healSpellVerified':True,
        'sourceHashes':{'Prerequisite.tbl':prereqs.sha256,'Spell4Effects.tbl':effects.sha256,
            'Spell4.tbl':spells.sha256,'Spell4Base.tbl':bases.sha256,'GameFormula.tbl':formulas.sha256},
        'dbcVerification':dbc_receipts,'prerequisites':out,'warriorProxies':selected,
        'spellCatalog':{'instances':instances,'baseTiers':tiers,'runtimeReady':False},
        'nativeAmountProbe':{'testOnly':True,'effect':direct,
            'effectFloatBits':effects.float_bits.get(89943,{}),
            'formula1266':{'assault':formula['datafloat0'],'support':formula['datafloat01']},
            'rawFormula':formula,'formulaFloatBits':formulas.float_bits.get(1266,{})}}

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--client',type=Path,default=ROOT/'WoWClient')
    ap.add_argument('--core',type=Path,required=True)
    ap.add_argument('--output',type=Path,required=True)
    args=ap.parse_args();data=build(args.client,args.core)
    args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text('-- Generated by tools/ws_combat_data.py; diagnostics only.\nreturn '+lua(data)+'\n',encoding='utf-8')
    args.output.with_suffix('.json').write_text(json.dumps(data,indent=2),encoding='utf-8')
    print('Wrote native diagnostic fixtures; Heal 2050 verified in both DBCs; no runtime spell installed')
if __name__=='__main__':main()
