"""Compile the in-repo D3D9 cloud adaptation into an embedded bytecode header.
Requires Windows D3DCompiler_47; no runtime compiler or loose shader is needed.
"""
import ctypes
import hashlib
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'wowdecomp/WoW/Source/WorldClient/Shaders/WildStarCloud.hlsl'
TARGET=SOURCE.with_name('WildStarCloudBytecode.h')

def blob_data(blob):
    table=ctypes.cast(ctypes.cast(blob,ctypes.POINTER(ctypes.c_void_p))[0],ctypes.POINTER(ctypes.c_void_p))
    pointer=ctypes.WINFUNCTYPE(ctypes.c_void_p,ctypes.c_void_p)(table[3])(blob)
    size=ctypes.WINFUNCTYPE(ctypes.c_size_t,ctypes.c_void_p)(table[4])(blob)
    data=ctypes.string_at(pointer,size)
    ctypes.WINFUNCTYPE(ctypes.c_ulong,ctypes.c_void_p)(table[2])(blob)
    return data

def compile_shader(source,profile):
    dll=ctypes.WinDLL('D3DCompiler_47.dll');f=dll.D3DCompile
    f.argtypes=[ctypes.c_void_p,ctypes.c_size_t,ctypes.c_char_p,ctypes.c_void_p,ctypes.c_void_p,
                ctypes.c_char_p,ctypes.c_char_p,ctypes.c_uint,ctypes.c_uint,
                ctypes.POINTER(ctypes.c_void_p),ctypes.POINTER(ctypes.c_void_p)]
    f.restype=ctypes.c_long
    code,error=ctypes.c_void_p(),ctypes.c_void_p()
    hr=f(source,len(source),str(SOURCE).encode(),None,None,b'main',profile.encode(),1<<15,0,ctypes.byref(code),ctypes.byref(error))
    message=blob_data(error).decode(errors='replace') if error else ''
    if hr<0:raise RuntimeError(message)
    if message:print(message)
    return blob_data(code)

def main():
    source=SOURCE.read_bytes();parts=['// Generated by tools/build_sky_shaders.py; source SHA256 '+hashlib.sha256(source).hexdigest(),
        '#pragma once','#include <cstdint>','namespace WildStarCloudBytecode {']
    for name,profile,prefix in [('Vertex','vs_3_0',b'#define VERTEX\n'),('Pixel','ps_3_0',b'')]:
        b=compile_shader(prefix+source,profile)
        parts.append('inline constexpr uint8_t '+name+'[] = {')
        parts.extend('    '+','.join(f'0x{x:02x}' for x in b[i:i+24])+',' for i in range(0,len(b),24))
        parts.append('};');print(profile,len(b),'bytes')
    parts.append('}')
    TARGET.write_text('\n'.join(parts)+'\n',encoding='utf-8')

if __name__=='__main__':main()
