#!/usr/bin/env python3
"""Find foreign keys between the dumped WildStar tables (WoWClient/tables_csv/*.csv, made by tools/tbl_dump.py).

A column references table T when almost all of its non-zero values are IDs of T (value containment) and, if possible, the column name contains the table name.
Writes docs/tbl_relations.json (all links) and docs/tbl_relations.md (summary).
Usage: tbl_relations.py [csv_dir] [min_containment=0.98]
"""
import csv, json, os, re, sys
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_DIR = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'WoWClient', 'tables_csv')
MIN = float(sys.argv[2]) if len(sys.argv) > 2 else 0.98
MIN_DISTINCT = 2


def to_int(s):
    try:
        return int(s)
    except ValueError:
        return None


def norm(s):
    return re.sub(r'[^a-z0-9]', '', s.lower())


tables = {}
for f in sorted(os.listdir(CSV_DIR)):
    if not f.endswith('.csv'):
        continue
    name = f[:-4]
    with open(os.path.join(CSV_DIR, f), newline='', encoding='utf-8', errors='replace') as fh:
        r = csv.reader(fh)
        head = next(r, None)
        if not head:
            continue
        rows = list(r)
    cols = {}
    for i, h in enumerate(head):
        vals = [to_int(row[i]) for row in rows if i < len(row) and row[i] != '']
        if vals and all(v is not None for v in vals):
            cols[h] = np.array(vals, dtype=np.int64)
    tables[name] = {'head': head, 'rows': len(rows), 'cols': cols}

ids = {}
for name, t in tables.items():
    c = t['cols'].get('ID')
    if c is not None and len(c):
        ids[name] = np.unique(c)

links = []
for name, t in tables.items():
    for col, v in t['cols'].items():
        if col == 'ID':
            continue
        nz = np.unique(v[v > 0])
        if len(nz) < MIN_DISTINCT:
            continue
        lo, hi = nz[0], nz[-1]
        key = norm(col)
        best = []
        for other, oi in ids.items():
            if oi[0] > lo or oi[-1] < hi:
                continue
            hit = np.isin(nz, oi).mean()
            if hit < MIN:
                continue
            cover = len(nz) / len(oi)   # how much of the other table is used (a tiny table matches by accident)
            named = norm(other) in key or (key.endswith('id') and key[:-2] and key[:-2] in norm(other))
            best.append((named, hit, cover, other))
        if not best:
            continue
        best.sort(key=lambda b: (b[0], b[1], b[2]), reverse=True)
        named_hits = [b for b in best if b[0]]
        pick = named_hits[:1] if named_hits else best[:3]
        for named, hit, cover, other in pick:
            if not named and len(oi := ids[other]) < 8:
                continue
            links.append({'table': name, 'column': col, 'target': other, 'containment': round(float(hit), 4), 'distinct': int(len(nz)),
                          'coverage': round(float(cover), 4), 'nameMatch': bool(named)})

out = os.path.join(ROOT, 'docs')
with open(os.path.join(out, 'tbl_relations.json'), 'w', encoding='utf-8') as f:
    json.dump(links, f, indent=1)

named = [l for l in links if l['nameMatch']]
guess = [l for l in links if not l['nameMatch']]
with open(os.path.join(out, 'tbl_relations.md'), 'w', encoding='utf-8') as f:
    f.write('# WildStar table relations (generated by tools/tbl_relations.py)\n\n')
    f.write('%d tables, %d with an ID column, %d links with the table name in the column name, %d value-only guesses (containment >= %.2f).\n\n' % (len(tables), len(ids), len(named), len(guess), MIN))
    f.write('## Name + value matches\n\n| table.column | -> table | containment | distinct |\n|---|---|---|---|\n')
    for l in sorted(named, key=lambda l: (l['table'], l['column'])):
        f.write('| %s.%s | %s | %.3f | %d |\n' % (l['table'], l['column'], l['target'], l['containment'], l['distinct']))
    f.write('\n## Value-only guesses (check by hand)\n\n| table.column | -> table | containment | distinct | coverage |\n|---|---|---|---|---|\n')
    for l in sorted(guess, key=lambda l: (l['table'], l['column'])):
        f.write('| %s.%s | %s | %.3f | %d | %.3f |\n' % (l['table'], l['column'], l['target'], l['containment'], l['distinct'], l['coverage']))
print(len(tables), 'tables', len(ids), 'with ID', len(named), 'named links', len(guess), 'guesses')
