"""Compile Engine/Source/Model2/Shaders/WildStarModel.hlsl into an embedded bytecode header (ps_3_0 variants). Needs Windows D3DCompiler_47."""
import ctypes, hashlib, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_sky_shaders as base

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'wowdecomp/Engine/Source/Model2/Shaders/WildStarModel.hlsl'
TARGET = SOURCE.with_name('WildStarModelBytecode.h')
# variant = vsn | normalmap<<1 | alphatest<<2 | layered<<3 | skinfx<<4; normalmap and layered require vsn
VARIANTS = [(v & 1, (v >> 1) & 1, (v >> 2) & 1, (v >> 3) & 1, (v >> 4) & 1) for v in range(32) if v & 1 or not (v & 2 or v & 8)]

def main():
    base.SOURCE = SOURCE
    src = SOURCE.read_bytes()
    parts = ['// Generated by tools/build_ws_model_shader.py; source SHA256 ' + hashlib.sha256(src).hexdigest(), '#pragma once', '#include <cstdint>', 'namespace WildStarModelBytecode {']
    valid = set()
    for vsn, nm, at, ly, fx in VARIANTS:
        v = vsn | nm << 1 | at << 2 | ly << 3 | fx << 4
        valid.add(v)
        pre = (b'#define WS_VSN\n' if vsn else b'') + (b'#define WS_NORMALMAP\n' if nm else b'') + (b'#define WS_ALPHATEST\n' if at else b'') + (b'#define WS_LAYERED\n' if ly else b'') + (b'#define WS_SKINFX\n' if fx else b'')
        code = base.compile_shader(pre + src, 'ps_3_0')
        parts.append('inline constexpr uint8_t Pixel%d[] = {' % v)
        parts.extend('    ' + ','.join(f'0x{x:02x}' for x in code[i:i + 24]) + ',' for i in range(0, len(code), 24))
        parts.append('};')
        print(v, len(code), 'bytes')
    parts.append('inline constexpr const uint8_t* Pixel[32] = {' + ','.join('Pixel%d' % v if v in valid else 'nullptr' for v in range(32)) + '};')
    parts.append('inline constexpr unsigned PixelSize[32] = {' + ','.join('sizeof(Pixel%d)' % v if v in valid else '0' for v in range(32)) + '};')
    parts.append('}')
    TARGET.write_text('\n'.join(parts) + '\n', encoding='utf-8')

if __name__ == '__main__':
    main()
