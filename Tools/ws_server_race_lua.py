#!/usr/bin/env python3
"""Generates an Eluna script that sets the display ids of the WildStar races (ChrRaces id >= 22) on the server.

The AzerothCore core sends stock WoW displays for these races (Mechari -> human male 3827, Cassian female -> tauren female 3770, ...) although the server's ChrRaces.dbc
holds the WildStar ones. The script sets display and native display id from the ChrRaces rows of the server's Data/dbc on login, first login, character creation, map change
and zone change.
usage: ws_server_race_lua.py --server "<AzerothCore folder>" [--out <file>]   (default: <server>\\Core\\lua_scripts\\WildStarRaceDisplay.lua)
"""
import argparse
import os
import struct

ap = argparse.ArgumentParser()
ap.add_argument('--server', required=True)
ap.add_argument('--out')
a = ap.parse_args()
dbc = os.path.join(a.server, 'Data', 'dbc', 'ChrRaces.dbc')
b = open(dbc, 'rb').read()
magic, rc, fc, rs, ss = struct.unpack_from('<4s4I', b, 0)
strings = b[20 + rc * rs:]
rows = []

for i in range(rc):
    r = struct.unpack_from('<%dI' % fc, b, 20 + i * rs)

    if r[0] >= 22 and r[4] and r[5]:
        name = strings[r[14]:strings.find(b'\0', r[14])].decode('latin1')
        rows.append((r[0], name, r[4], r[5]))

lines = [
    '-- generated by tools/ws_server_race_lua.py from Data/dbc/ChrRaces.dbc: WildStar race displays (the core sends stock WoW displays for these races)',
    'local ON_FIRST_LOGIN, ON_LOGIN, ON_CHARACTER_CREATE, ON_UPDATE_ZONE, ON_MAP_CHANGE = 30, 3, 1, 27, 28',
    '',
    'local DISPLAYS = {',
]
lines += ['\t[%d] = { %d, %d },   -- %s (male, female)' % (race, male, female, name) for race, name, male, female in rows]
lines += [
    '}',
    '',
    'local function Apply(player)',
    '\tif not player then return end',
    '\tif WildStarAppearance and WildStarAppearance.HasProfile(player) then WildStarAppearance.Apply(player); return end',
    '\tlocal d = DISPLAYS[player:GetRace()]',
    '\tif not d then return end',
    '\tlocal id = d[player:GetGender() + 1]',
    '\tif not id then return end',
    '\tlocal oldNative = player:GetNativeDisplayId()',
    '\tprint(string.format("[WildStarRaceDisplay] %s race %d gender %d class %d native %d display %d -> %d", player:GetName(), player:GetRace(), player:GetGender(), player:GetClass(), oldNative, player:GetDisplayId(), id))',
    '\tif oldNative ~= id then player:SetNativeDisplayId(id) end',
    '\t-- only replace the core display (= the old native one); mounts, shapeshifts and morphs have a different display and stay',
    '\tif oldNative ~= id and player:GetDisplayId() == oldNative then player:SetDisplayId(id) end',
    'end',
    '',
    'local function Later(event, player)',
    '\tApply(player)',
    '\tplayer:RegisterEvent(function(_, _, _, p) Apply(p) end, 1500, 1)',
    'end',
    '',
    'RegisterPlayerEvent(ON_LOGIN, Later)',
    'RegisterPlayerEvent(ON_FIRST_LOGIN, Later)',
    'RegisterPlayerEvent(ON_CHARACTER_CREATE, function(event, player) Apply(player) end)',
    'RegisterPlayerEvent(ON_UPDATE_ZONE, function(event, player) Apply(player) end)',
    'RegisterPlayerEvent(ON_MAP_CHANGE, function(event, player) Apply(player) end)',
    '',
]
out = a.out or os.path.join(a.server, 'Core', 'lua_scripts', 'WildStarRaceDisplay.lua')
open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
print('wrote', out, '(%d races)' % len(rows))

# creature_model_info rows of the race displays: Gender 0 / 1 (the core copies the model's gender into the unit's gender byte; the NPC rows of ws_spawns.py use 2 = none)
sql = os.path.join(os.path.dirname(out), '..', '..', '..', '..', 'build_wildstar') if False else None
rows_sql = []
for race, name, male, female in rows:
    if male != female:
        rows_sql.append('(%d, 0.4, 1.5, 0, %d, 0)' % (male, female))
        rows_sql.append('(%d, 0.35, 1.5, 1, %d, 0)' % (female, male))
    else:
        rows_sql.append('(%d, 0.3, 1.5, 0, 0, 0)' % male)
seen = {}
for r in rows_sql:
    seen[r.split(',')[0]] = r
sqlfile = os.path.splitext(out)[0] + '_model_info.sql'
NL = chr(10)
head = '-- gender of the WildStar race displays (see tools/ws_server_race_lua.py)' + NL
head += 'INSERT INTO `creature_model_info` (`DisplayID`, `BoundingRadius`, `CombatReach`, `Gender`, `DisplayID_Other_Gender`, `VerifiedBuild`) VALUES' + NL
tail = NL + 'ON DUPLICATE KEY UPDATE `Gender` = VALUES(`Gender`), `DisplayID_Other_Gender` = VALUES(`DisplayID_Other_Gender`);' + NL
open(sqlfile, 'w', encoding='utf-8').write(head + (',' + NL).join(seen.values()) + tail)
print('wrote', sqlfile)
